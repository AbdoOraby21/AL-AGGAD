export type DictKey = keyof (typeof dict)['en'];

export function t(locale: Locale, key: DictKey): string {
  return (dict[locale] as Record<string, string>)[key] ?? (dict.en as Record<string, string>)[key] ?? key;
}

export function dressName(d: { name_ar: string; name_en: string }, locale: Locale): string {
  return locale === 'ar' ? d.name_ar : d.name_en;
}

/** Documented RTL/LTR contract: Arabic renders right-to-left, English left-to-right. */
export function localeDir(locale: Locale): 'rtl' | 'ltr' {
  return locale === 'ar' ? 'rtl' : 'ltr';
}
